/**
 * Sets up a hosted Neon instance for the three services.
 *
 * Why this is not the same script as the local Docker setup:
 *
 *   - Neon routes DDL through a control plane, so a role's password must meet
 *     its policy: long, mixed case, digits and special characters.
 *   - Neon's pooler rejects `search_path` in the startup parameters, so the
 *     schema is set on the ROLE instead (ALTER ROLE ... SET search_path),
 *     which the pooler does apply.
 *   - The role is restricted to its own schema and cannot write to `public`,
 *     so the isolation is enforced by PostgreSQL rather than by convention.
 *
 * Usage:
 *   DATABASE_URL=<the Neon owner URL> pnpm db:setup:neon
 *
 * The generated per-service URLs are written to .env.render, which is
 * gitignored, so the passwords do not end up in a terminal scrollback or in
 * the repository.
 */
import { randomBytes } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const here = dirname(fileURLToPath(import.meta.url));
const outputFile = join(here, '..', '..', '.env.render');

const SERVICES = [
  { name: 'lost-found', schema: 'lost_found', role: 'lost_found_role' },
  { name: 'auth', schema: 'auth', role: 'auth_role' },
  { name: 'flash-sale', schema: 'flash_sale', role: 'flash_sale_role' },
];

const connectionString = process.env.DATABASE_URL;
if (!connectionString) {
  console.error('DATABASE_URL is required — the Neon owner connection string.');
  process.exit(1);
}

/** A password that satisfies Neon's policy: long, mixed, with symbols. */
const strongPassword = () =>
  `${randomBytes(18).toString('base64url')}Aa1!`;

const client = new pg.Client({ connectionString, connectionTimeoutMillis: 20_000 });

try {
  await client.connect();
  console.log('[neon] connected');

  const urls = {};

  for (const service of SERVICES) {
    const password = strongPassword();

    // The role. CREATE ROLE has no IF NOT EXISTS, so it is done conditionally.
    await client.query(`
      DO $do$
      BEGIN
        IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${service.role}') THEN
          CREATE ROLE ${service.role} LOGIN PASSWORD '${password}';
        ELSE
          ALTER ROLE ${service.role} PASSWORD '${password}';
        END IF;
      END
      $do$;
    `);

    // The owner is not a superuser on Neon, so it must be a member of the
    // role before it can assign ownership of a schema to it.
    await client.query(`GRANT ${service.role} TO neondb_owner`);

    // The schema, owned by the role.
    await client.query(
      `CREATE SCHEMA IF NOT EXISTS ${service.schema} AUTHORIZATION ${service.role}`,
    );

    // The search path is set on the ROLE, because Neon's pooler refuses
    // `search_path` in the startup parameters but does apply role settings.
    await client.query(
      `ALTER ROLE ${service.role} SET search_path TO ${service.schema}, public`,
    );

    // CONNECT on the database itself. A role with no CONNECT privilege
    // cannot reach the database at all, whatever it owns inside it.
    await client.query(`GRANT CONNECT ON DATABASE neondb TO ${service.role}`);

    await client.query(`GRANT USAGE ON SCHEMA ${service.schema} TO ${service.role}`);
    await client.query(`GRANT ALL ON SCHEMA ${service.schema} TO ${service.role}`);

    // The role may not touch anything else.
    await client.query(`REVOKE ALL ON SCHEMA public FROM ${service.role}`);

    // A test schema, owned by the same role.
    await client.query(
      `CREATE SCHEMA IF NOT EXISTS ${service.schema}_test AUTHORIZATION ${service.role}`,
    );
    await client.query(
      `GRANT ALL ON SCHEMA ${service.schema}_test TO ${service.role}`,
    );

    const url = new URL(connectionString);
    url.username = service.role;
    url.password = password;

    urls[service.name] = {
      DATABASE_URL: url.toString(),
      schema: service.schema,
      role: service.role,
    };

    console.log(`[neon] ${service.role} -> schema ${service.schema}`);
  }

  // The secrets go to a gitignored file, not to the terminal.
  //
  // The file contains everything Render needs, per service, so it can be
  // copied and pasted without a secret ever appearing in a terminal
  // scrollback or in the repository.
  const jwtSecret = randomBytes(48).toString('base64url');

  const body = [
    '# Generated by scripts/db/setup-neon.mjs — GITIGNORED, do not commit.',
    '#',
    '# One block per service. Copy the variables into that service on Render.',
    '#',
    '# CORS_ORIGINS is a placeholder: replace it with your deployed portfolio',
    '# origin once you have it, then redeploy the service.',
    '',
    ...SERVICES.flatMap((service) => [
      `# ============================================================`,
      `# ${service.name}  (role ${service.role}, schema ${service.schema})`,
      `# ============================================================`,
      `NODE_ENV=production`,
      `PORT=10000`,
      `DATABASE_URL=${urls[service.name].DATABASE_URL}`,
      `JWT_SECRET=${jwtSecret}`,
      `JWT_ISSUER=gip-auth`,
      `JWT_AUDIENCE=gip`,
      `CORS_ORIGINS=http://localhost:5173`,
      `RUN_MIGRATIONS=true`,
      '',
    ]),
  ].join('\n');

  await writeFile(outputFile, body, 'utf8');

  console.log(`\n[neon] ready. The environment blocks are in ${outputFile}`);
  console.log('[neon] that file is gitignored — it is not in the repository.');
  console.log('[neon] all three services share one JWT_SECRET, so the auth');
} catch (error) {
  console.error('[neon] failed:', error instanceof Error ? error.message : error);
  process.exitCode = 1;
} finally {
  await client.end();
}
